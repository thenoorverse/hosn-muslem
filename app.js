let activeCat = "all";
let counts = {};
try{ counts = JSON.parse(localStorage.getItem("hisn-counts")||"{}"); }catch(e){ counts={}; }
let fontSize = parseInt(localStorage.getItem("hisn-fs")||"19",10);

function save(){ try{localStorage.setItem("hisn-counts",JSON.stringify(counts));}catch(e){} }
function applyFs(){ document.documentElement.style.setProperty("--fs", fontSize+"px"); try{localStorage.setItem("hisn-fs",fontSize);}catch(e){} }

function renderCats(){
  const box = document.getElementById("cats");
  box.innerHTML = "";
  CATS.forEach(c=>{
    const n = c.id==="all" ? DATA.length : DATA.filter(d=>d.cat===c.id).length;
    const b = document.createElement("button");
    b.textContent = c.name+" ("+n+")";
    if(c.id===activeCat) b.classList.add("active");
    b.onclick = ()=>{ activeCat=c.id; renderCats(); render(); window.scrollTo({top:document.querySelector("main").offsetTop-10,behavior:"smooth"}); };
    box.appendChild(b);
  });
}

function hi(text,q){
  if(!q) return text;
  const esc = q.replace(/[.*+?^${}()|[\]\\]/g,"\\$&");
  return text.replace(new RegExp("("+esc+")","g"),"<mark>$1</mark>");
}

function render(){
  applyFs();
  const q = (document.getElementById("search").value||"").trim();
  const wrap = document.getElementById("sections");
  wrap.innerHTML = "";
  let list = DATA.map((d,i)=>({...d,idx:i}));
  if(activeCat!=="all") list = list.filter(d=>d.cat===activeCat);
  if(q) list = list.filter(d=>(d.title+d.text+(d.virtue||"")).includes(q));
  document.getElementById("statCount").textContent = "عدد الأذكار في الموقع: "+DATA.length;
  document.getElementById("statCats").textContent = "عدد الأقسام: "+(CATS.length-1);
  document.getElementById("results-info").textContent = q ? ("نتائج البحث عن «"+q+"»: "+list.length) : (activeCat==="all" ? "" : ("القسم: "+(CATS.find(c=>c.id===activeCat)||{}).name+" — "+list.length+" ذكراً"));

  const groups = activeCat==="all" ? CATS.filter(c=>c.id!=="all") : CATS.filter(c=>c.id===activeCat);
  groups.forEach(g=>{
    const items = list.filter(d=>d.cat===g.id);
    if(!items.length) return;
    const h = document.createElement("div");
    h.className="sec-title";
    h.innerHTML = "<h2>"+g.name+"</h2><span class='count'>"+items.length+"</span>";
    wrap.appendChild(h);
    if(CAT_DESC[g.id]){ const p=document.createElement("p"); p.className="sec-desc"; p.textContent=CAT_DESC[g.id]; wrap.appendChild(p); }
    items.forEach(d=>{
      const card = document.createElement("article");
      card.className="zikr";
      const key = "z"+d.idx;
      const c = counts[key]||0;
      card.innerHTML =
        "<div class='zikr-head'><h3>"+(d.idx+1)+". "+hi(d.title,q)+"</h3><span class='rep'>🔁 "+d.repeat+"</span></div>"+
        "<div class='text'>"+hi(d.text,q)+"</div>"+
        (d.virtue?("<div class='virtue'>⭐ الفضل: "+hi(d.virtue,q)+"</div>"):"")+
        "<div class='zikr-actions'>"+
          "<button class='counter' data-k='"+key+"'>العداد: "+c+"</button>"+
          "<button data-copy>📋 نسخ الذكر</button>"+
          "<button data-done>✔ تم قراءته</button>"+
        "</div>";
      const btnC = card.querySelector(".counter");
      btnC.onclick = ()=>{ counts[key]=(counts[key]||0)+1; save(); btnC.textContent="العداد: "+counts[key]; };
      btnC.ondblclick = ()=>{ counts[key]=0; save(); btnC.textContent="العداد: 0"; };
      card.querySelector("[data-copy]").onclick = (e)=>{
        const t = d.title+"\n"+d.text+"\n(التكرار: "+d.repeat+")";
        navigator.clipboard.writeText(t).then(()=>{ e.target.textContent="✅ تم النسخ"; setTimeout(()=>e.target.textContent="📋 نسخ الذكر",1500); });
      };
      const btnD = card.querySelector("[data-done]");
      if(counts[key+"_done"]){ btnD.classList.add("done"); btnD.textContent="✔ مقروء"; }
      btnD.onclick = ()=>{
        if(counts[key+"_done"]){ delete counts[key+"_done"]; btnD.classList.remove("done"); btnD.textContent="✔ تم قراءته"; }
        else{ counts[key+"_done"]=1; btnD.classList.add("done"); btnD.textContent="✔ مقروء"; }
        save();
      };
      wrap.appendChild(card);
    });
  });
  if(!list.length){
    wrap.innerHTML = "<div class='card'>لا توجد نتائج مطابقة. جرّب كلمة أخرى مثل: صباح، نوم، سفر، هم.</div>";
  }
}

